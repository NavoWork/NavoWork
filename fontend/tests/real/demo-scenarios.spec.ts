import { expect, test } from '@playwright/test';

test('create independent demo inquiries and use real Agent chat from both views', async ({ page }) => {
  const serverErrors: string[] = [];
  page.on('response', response => { if (response.status() >= 500) serverErrors.push(response.url()); });
  await page.goto('/');
  await page.getByLabel('账号邮箱').fill('demo@navowork.local');
  await page.getByLabel('密码').fill('ChangeMe123!');
  await page.getByRole('button', { name: '登录工作空间' }).click();
  await page.getByRole('button', { name: '新建询盘', exact: true }).click();
  const modal = page.getByRole('dialog', { name: '新建询盘' });
  await expect(modal.getByRole('radio')).toHaveCount(5);
  await modal.getByRole('button', { name: '空白询盘' }).click();
  await modal.getByLabel('客户原文').fill('My own original inquiry');
  await modal.getByRole('button', { name: '演示询盘', exact: true }).click();
  await modal.getByRole('radio', { name: /日本/ }).check();
  await modal.getByRole('button', { name: '空白询盘' }).click();
  await expect(modal.getByLabel('客户原文')).toHaveValue('My own original inquiry');
  await modal.getByRole('button', { name: '演示询盘', exact: true }).click();
  const created = page.waitForResponse(r => r.url().endsWith('/inquiries') && r.request().method() === 'POST');
  await modal.getByRole('button', { name: '创建演示询盘' }).click();
  const inquiry = await (await created).json();
  expect(inquiry.demoScenarioId).toBe('jp-cooler');
  expect(inquiry.demoDataScope).toBe('reference');
  expect(inquiry.originalText).toContain('4,000');
  expect(inquiry.currentRevision).toBe(0);
  await expect(page).toHaveURL(new RegExp(`/inquiries/${inquiry.id}$`));
  await expect(page.locator('.react-flow__node:visible')).toHaveCount(2);
  const chat = page.locator('.iw-assistant');
  const input = chat.getByLabel('补充要求或客户反馈');
  await expect(page.getByText('真实服务 · 服务端保存', { exact: true })).toHaveCount(0);
  await expect(chat.getByRole('button', { name: /产品生图/ })).toBeEnabled();
  await chat.getByRole('button', { name: /产品生图/ }).click();
  await expect(input).toHaveValue(/产品概念图/);
  await chat.getByRole('button', { name: '分析询盘', exact: true }).click();
  await expect(input).toHaveValue(/整理客户需求/);
  await page.getByRole('button', { name: '业务流程', exact: true }).click();
  await expect(input).toHaveValue(/整理客户需求/);
  await expect(chat.getByText('试试 AI 能力', { exact: true })).toBeVisible();
  await expect(chat.getByLabel('路演下一步')).toHaveCount(0);
  await page.getByRole('button', { name: '资料画板', exact: true }).click();
  const dispatch = page.waitForResponse(r => r.url().endsWith('/workbench/agent') && r.request().method() === 'POST');
  await chat.getByRole('button', { name: '开始处理', exact: true }).click();
  const runResponse = await dispatch;
  expect(runResponse.ok()).toBeTruthy();
  const run = await runResponse.json();
  expect(run.status).toBe('queued');
  await page.request.post(`/api/v1/workspaces/ws_demo/runs/${run.id}/cancel`);
  await page.getByRole('button', { name: '新建询盘', exact: true }).click();
  const secondCreated = page.waitForResponse(r => r.url().endsWith('/inquiries') && r.request().method() === 'POST');
  await modal.getByRole('radio', { name: /日本/ }).check();
  await modal.getByRole('button', { name: '创建演示询盘' }).click();
  const second = await (await secondCreated).json();
  expect(second.id).not.toBe(inquiry.id);
  expect(second.currentRevision).toBe(0);
  await expect(page).toHaveURL(new RegExp(`/inquiries/${second.id}$`));
  await expect(page.locator('.react-flow__node:visible')).toHaveCount(2);
  await expect.poll(async () => {
    const board = await page.locator('.ic-board:visible').boundingBox();
    const node = await page.locator('.react-flow__node:visible').nth(1).boundingBox();
    return { board, node, fits: !!board && !!node && node.x >= board.x && node.x + node.width <= board.x + board.width + 1 };
  }).toMatchObject({ fits: true });
  const nodeDispatch = page.waitForResponse(r => r.url().endsWith('/workbench/simulations') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '依据现有资料生成', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const nodeResponse = await nodeDispatch;
  expect(nodeResponse.ok()).toBeTruthy();
  expect(nodeResponse.request().postDataJSON().node).toBe('requirements');
  expect(nodeResponse.request().postDataJSON().contextScope).toBe('inquiry');
  const nodeRun = await nodeResponse.json();
  await page.request.post(`/api/v1/workspaces/ws_demo/runs/${nodeRun.id}/cancel`);
  // Ordinary inquiries use the same one-click path, without a source-selection modal.
  const blankResponse = await page.request.post('/api/v1/workspaces/ws_demo/inquiries', {
    data: { title: 'Blank inquiry generation', customer: 'Test buyer', originalText: 'Please quote 100 backpacks.' },
  });
  const blank = await blankResponse.json();
  await page.goto(`/inquiries/${blank.id}`);
  await expect(page.locator('.react-flow__node:visible')).toHaveCount(2);
  const blankDispatch = page.waitForResponse(r => r.url().endsWith('/workbench/simulations') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '依据现有资料生成', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const blankRunResponse = await blankDispatch;
  expect(blankRunResponse.ok()).toBeTruthy();
  expect(blankRunResponse.request().postDataJSON().node).toBe('requirements');
  await page.request.post(`/api/v1/workspaces/ws_demo/runs/${(await blankRunResponse.json()).id}/cancel`);
  expect(serverErrors).toEqual([]);
});
