import { expect, test } from '@playwright/test';

test('business settings, empty stages and generated documents work together', async ({ page }, info) => {
  await page.goto('/');
  await page.getByLabel('账号邮箱').fill('demo@navowork.local');
  await page.getByLabel('密码').fill('ChangeMe123!');
  await page.getByRole('button', { name: '登录工作空间' }).click();
  await expect(page.getByRole('navigation', { name: '主导航' })).toBeVisible();
  await page.getByRole('button', { name: '工作空间设置', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('公司名称').fill('Harbor Trade');
  await dialog.getByRole('button', { name: '保存设置' }).click();
  await expect(dialog.getByRole('status')).toContainText('设置已保存');
  await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: '工作空间设置', exact: true }).click();
  await expect(page.getByRole('dialog').getByLabel('公司名称')).toHaveValue('Harbor Trade');
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  const path = '/api/v1/workspaces/ws_demo/inquiries/inq_demo_bag';
  expect((await (await page.request.get(path + '/artifacts')).json()).items).toHaveLength(0);
  await page.goto('/inquiries/inq_demo_bag');
  await expect(page.getByLabel('业务流程').getByRole('button')).toHaveCount(7);
  await expect(page.getByLabel('业务流程').getByText('已有成果')).toHaveCount(0);
  await expect(page.getByLabel('业务流程')).toContainText('验货交付');
  const suggestions = page.getByRole('region', { name: '下一步消息建议' });
  await expect(suggestions.getByRole('button', { name: '整理客户需求' })).toBeVisible();
  let submittedRuns = 0;
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/runs')) submittedRuns += 1; });
  await suggestions.getByRole('button', { name: '整理客户需求' }).click();
  const composer = page.getByLabel('补充要求或客户反馈');
  await expect(composer).toBeFocused();
  await expect(composer).toHaveValue(/仅完成当前需求节点/);
  expect(submittedRuns).toBe(0);
  await composer.fill('');
  await page.screenshot({ path: info.outputPath('fresh-inquiry.png'), fullPage: true });
  const created = await page.request.post(path + '/artifacts', { data: { kind: 'spec', title: '背包规格书', content: { product: 'Backpack', quantity: 3000, material: '600D polyester', packaging: null } } });
  expect(created.ok()).toBeTruthy();
  await page.reload();
  await expect(suggestions.getByRole('button', { name: '准备供应商询价单' })).toBeVisible();
  await expect(suggestions.getByRole('button', { name: '整理客户需求' })).toHaveCount(0);
  await expect(page.locator('.react-flow__node[data-id="artifact:spec"]')).toContainText('背包规格书');
  await page.locator('.react-flow__node[data-id="artifact:spec"]').dblclick();
  await expect(page.locator('.ba-document')).toContainText('600D polyester');
  const download = page.waitForEvent('download');
  await page.locator('.ba-document').getByRole('button', { name: 'PDF', exact: true }).click();
  expect((await download).suggestedFilename()).toContain('背包规格书');
  await page.screenshot({ path: info.outputPath('business-document.png'), fullPage: true });
});
