from typing import Any, Callable, Protocol, runtime_checkable
from navowork_agent.contracts import ExecutionContext, FileRef, ToolResult, ExecutionEvent


@runtime_checkable
class CaseContextPort(Protocol):
    def context(self) -> ExecutionContext: ...
    def user_facts(self) -> dict[str, Any]: ...
    def assert_current(self) -> None: ...


@runtime_checkable
class FileStorePort(Protocol):
    def list_files(self) -> list[FileRef]: ...
    def read_bytes(self, file_id: str) -> bytes: ...
    def read_document(self, file_id: str) -> dict: ...


@runtime_checkable
class ArtifactTransaction(Protocol):
    """Atomic host unit of work used inside execute_once; no filesystem paths."""
    def current(self, artifact_id: str) -> dict | None: ...
    def put_file(self, data: bytes, name: str, role: str = "output") -> FileRef: ...
    def append_artifact(self, record: dict) -> None: ...
    def register_export(self, artifact: dict, file: FileRef) -> None: ...


@runtime_checkable
class ArtifactPort(Protocol):
    def list_artifacts(self) -> list[dict]: ...
    def get_artifact(self, artifact_id: str, version: int | None = None) -> dict: ...
    def list_exports(self, artifact_id: str, version: int) -> list[FileRef]: ...
    def execute_once(self, key: str, payload: dict, operation: Callable[[ArtifactTransaction], ToolResult], *, write: bool = True) -> ToolResult: ...


@runtime_checkable
class EventSink(Protocol):
    def emit(self, kind: str, summary: str, result_ref: str | None = None) -> ExecutionEvent: ...
